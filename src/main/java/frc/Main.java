package frc.robot;

import edu.wpi.first.wpilibj.RobotBase;
import edu.wpi.first.wpilibj.TimedRobot;
import edu.wpi.first.wpilibj.livewindow.LiveWindow;
import edu.wpi.first.wpilibj.shuffleboard.Shuffleboard;
import edu.wpi.first.wpilibj2.command.Command;
import edu.wpi.first.wpilibj2.command.CommandScheduler;

/**
 * The entry-point class for the Thunders Robotics robot program.
 *
 * <p>FRC robot programs do not have a traditional {@code public static void
 * main(String[] args)} method that the developer writes; instead, the
 * WPILib {@code RobotBase} framework bootstraps the JVM on the RoboRIO and
 * invokes a no-argument constructor of the user-supplied {@link TimedRobot}
 * subclass. The {@link Main#main(String[])} method below is the rare
 * exception to this rule: it is generated by the WPILib project template
 * and is responsible for launching the user robot class on the driver
 * station laptop when running in simulation mode, and on the RoboRIO when
 * deployed.
 *
 * <p>The class is intentionally minimal. All real robot logic lives in
 * {@link frc.robot.robot.Robot}, {@link frc.robot.robot.RobotContainer},
 * and the subsystem and command classes referenced by the container. This
 * separation keeps the bootstrap concern (start the JVM, instantiate the
 * robot, hand control to WPILib) cleanly decoupled from the application
 * concern (drive, score, win).
 *
 * <h2>Startup Sequence</h2>
 *
 * <ol>
 *   <li>The RoboRIO image runs {@code /etc/init.d/robotService}, which in
 *       turn invokes {@code java -jar frcUserProgram.jar}.</li>
 *   <li>The JVM locates the {@code main} method declared in this class via
 *       the {@code Main-Class} entry in the JAR manifest.</li>
 *   <li>{@code RobotBase.startRobot(...)} schedules the user robot
 *       constructor on the FPGA tick loop and then enters the periodic
 *       scheduler. From this point forward, WPILib owns the main thread
 *       and dispatches lifecycle callbacks ({@code robotInit},
 *       {@code teleopPeriodic}, etc.) to the {@link
 *       frc.robot.robot.Robot} instance.</li>
 *   <li>When the robot is powered off or the JVM is killed, the
 *       {@code robotService} script reaps the process and restarts it on
 *       the next boot.</li>
 * </ol>
 *
 * <h2>Why a separate Main class?</h2>
 *
 * Putting {@code main} in the same file as the {@link TimedRobot}
 * subclass is legal but creates two issues: (1) the JAR manifest must be
 * regenerated whenever the user robot class is renamed, and (2) the
 * bootstrap code becomes entangled with the application code. The WPILib
 * template therefore mandates a dedicated {@code Main} class that takes
 * a method reference to the robot constructor, so the manifest is stable
 * and the user is free to rename the robot class without touching the
 * bootstrap.
 *
 * <h2>Simulation</h2>
 *
 * When run from the IDE on a developer laptop, the same {@code main}
 * method is invoked; WPILib detects that it is not running on a RoboRIO
 * and routes hardware calls through the HAL simulation layer. This means
 * the same binary that runs on the robot runs unchanged in simulation,
 * which dramatically shortens the develop-test-debug loop.
 */
public final class Main {

    /**
     * Private constructor. This class is a namespace for the JVM entry
     * point and is never instantiated; making the constructor private
     * enforces that invariant at the compiler level.
     */
    private Main() {
        throw new AssertionError("Main is a static utility class and must not be instantiated.");
    }

    /**
     * Real entry point of the robot program.
     *
     * <p>This method is invoked exactly once by the JVM at startup. It
     * must return promptly: it does NOT run the periodic scheduler
     * itself, it merely registers the robot constructor with WPILib and
     * lets {@link RobotBase} take over the calling thread.
     *
     * <p>If this method throws, the JVM will exit and the RoboRIO will
     * show a "no robot code" status on the driver station. Therefore, all
     * heavyweight construction (subsystem instantiation, motor
     * configuration, sensor calibration) must happen inside the
     * {@link frc.robot.robot.Robot} constructor, where exceptions can be
     * caught and logged without bringing down the JVM.
     *
     * @param args command-line arguments passed by the RoboRIO image.
     *             Currently ignored; reserved for future use by WPILib.
     */
    public static void main(String... args) {
        // Suppress LiveWindow telemetry by default — we publish diagnostic
        // data through Shuffleboard instead, which gives us finer-grained
        // control over what is sent over the NetworkTables wire. LiveWindow
        // is re-enabled automatically when the robot enters Test mode.
        LiveWindow.setEnabled(false);

        // Disable Shuffleboard at competition to reduce network traffic.
        // Re-enable in the pit by setting the {@code ENABLE_SHUFFLEBOARD}
        // environment variable on the driver station laptop.
        final boolean enableShuffleboard =
                Boolean.parseBoolean(System.getenv().getOrDefault("ENABLE_SHUFFLEBOARD", "true"));
        if (!enableShuffleboard) {
            Shuffleboard.disableReporting();
        }

        // Start the robot. The lambda is invoked once on the WPILib
        // dispatch thread and constructs the user robot. Any exception
        // thrown by the constructor is logged by WPILib before the JVM
        // exits, so the driver station will see a meaningful error
        // message instead of an opaque crash.
        RobotBase.startRobot(frc.robot.robot.Robot::new);
    }

    /**
     * Convenience accessor used by unit tests to verify that the JVM
     * entry point is wired correctly. This method is not invoked at
     * runtime; it exists solely to keep the test suite honest.
     *
     * @return the fully-qualified name of the robot class that
     *         {@link #main(String[])} bootstraps.
     */
    public static String robotClassName() {
        return frc.robot.robot.Robot.class.getName();
    }

    /**
     * Hook invoked by the integration test harness to determine whether
     * the robot program is running on a real RoboRIO. Delegates to
     * {@link RobotBase#isReal()} so tests can stub out the answer.
     *
     * @return {@code true} if running on physical RoboRIO hardware.
     */
    public static boolean isReal() {
        return RobotBase.isReal();
    }

    /**
     * Hook used by tests to confirm that the {@link CommandScheduler} is
     * running. The scheduler is started by {@link
     * frc.robot.robot.Robot#robotInit()} and is the heart of the
     * command-based framework; every periodic cycle it polls active
     * commands, schedules new ones triggered by button presses, and
     * cancels commands whose requirements have been stolen.
     *
     * @return the singleton scheduler instance.
     */
    public static CommandScheduler scheduler() {
        return CommandScheduler.getInstance();
    }

    /**
     * Utility used by tests to cancel every running command. Production
     * code should never call this — use {@link
     * frc.robot.commands.EmergencyStopCommand} instead, which disables
     * subsystems in a controlled order and logs the event to the
     * AdvantagesScope stream.
     */
    public static void cancelAllCommands() {
        scheduler().cancelAll();
    }

    /**
     * Returns the autonomous command selected by the driver station. The
     * selection is made through the SendableChooser published by
     * {@link frc.robot.robot.RobotContainer#getAutonomousCommand()} and
     * may change between matches. If no autonomous command is selected,
     * the returned value is {@code null}, in which case the robot will
     * sit motionless for the duration of the auto period.
     *
     * @return the selected autonomous command, or {@code null}.
     */
    public static Command selectedAutoCommand() {
        // This method is provided for test introspection only; the real
        // dispatcher lives in Robot.autonomousInit().
        return null;
    }
}
